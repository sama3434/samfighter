export const GLYPH_W = 5, GLYPH_H = 7, GLYPH_GAP = 1;

export function textWidth(str, scale = 1) {
  return String(str).length * (GLYPH_W + GLYPH_GAP) * scale - GLYPH_GAP * scale;
}

/** align: 'left' | 'center' | 'right'; `shadow` draws a 1px offset copy behind. */
export function drawText(c, str, x, y, col, scale = 1, align = 'left', shadow = null) {
  str = String(str).toUpperCase();
  let sx = x;
  if (align === 'center') sx = x - textWidth(str, scale) / 2;
  else if (align === 'right') sx = x - textWidth(str, scale);
  sx = Math.round(sx);
  y = Math.round(y);

  for (const pass of shadow ? [shadow, null] : [null]) {
    const off = pass ? scale : 0;
    const colour = pass || col;
    let cx = sx + off;
    for (const ch of str) {
      const g = GLYPHS[ch] || GLYPHS[' '];
      for (let r = 0; r < GLYPH_H; r++) {
        for (let q = 0; q < GLYPH_W; q++) {
          if (g[r][q] === '#') {
            c.fillStyle = colour;
            c.fillRect(cx + q * scale, y + off + r * scale, scale, scale);
          }
        }
      }
      cx += (GLYPH_W + GLYPH_GAP) * scale;
    }
  }
}
